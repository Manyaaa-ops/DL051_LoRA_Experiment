"""Generate LaTeX macros + result tables from results/results.csv.

Writes into report/generated/ so report.tex never contains hand-copied
numbers: every table value in the report is produced by this script from
the actual experiment logs (results.csv + experiment_log.csv).

Usage:  .venv/bin/python scripts/report_tables.py
"""

from __future__ import annotations

import os
import sys

import pandas as pd

RUN_ORDER = ["full", "lora_r2_a4", "lora_r4_a8", "lora_r8_a16"]
RUN_LABEL = {
    "full": r"Full FT",
    "lora_r2_a4": r"LoRA $r{=}2$",
    "lora_r4_a8": r"LoRA $r{=}4$",
    "lora_r8_a16": r"LoRA $r{=}8$",
}
# Macro suffixes must be letters only (digits would terminate a LaTeX control word)
RUN_MACRO = {"full": "FULL", "lora_r2_a4": "RTWO",
             "lora_r4_a8": "RFOUR", "lora_r8_a16": "REIGHT"}

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "report", "generated")


def esc(x) -> str:
    return str(x).replace("_", r"\_")


def fmt_mem(v) -> str:
    try:
        return f"{float(v):.0f}"
    except (TypeError, ValueError):
        return "n/a"


def main() -> int:
    os.makedirs(OUT, exist_ok=True)
    df = pd.read_csv(os.path.join(ROOT, "results", "results.csv"))
    df["peak_gpu_mem_mib"] = pd.to_numeric(df["peak_gpu_mem_mib"], errors="coerce")
    # keep the best/latest row per run name
    df = df.drop_duplicates(subset=["run_name"], keep="last")
    df["_o"] = df["run_name"].map(lambda n: RUN_ORDER.index(n) if n in RUN_ORDER else 99)
    d = df.sort_values("_o").set_index("run_name")
    assert set(RUN_ORDER) <= set(d.index), f"missing runs: {set(RUN_ORDER) - set(d.index)}"
    device = df["device"].iloc[0]

    # ---- macros ---------------------------------------------------------
    lines = [
        "% AUTO-GENERATED by scripts/report_tables.py -- do not edit by hand.",
        f"% device={device}, source=results/results.csv",
    ]
    for name, macro in RUN_MACRO.items():
        r = d.loc[name]
        mem = r["peak_gpu_mem_mib"]
        lines += [
            rf"\newcommand{{\Val{macro}}}{{{float(r['best_val_acc'])*100:.2f}\%}}",
            rf"\newcommand{{\Tp{macro}}}{{{int(r['total_params']):,}}}".replace(",", ","),
            rf"\newcommand{{\Trainp{macro}}}{{{int(r['trainable_params']):,}}}".replace(",", ","),
            rf"\newcommand{{\Trainpc{macro}}}{{{float(r['trainable_pct']):.3f}\%}}",
            rf"\newcommand{{\Time{macro}}}{{{float(r['train_time_sec'])/60:.1f}}}",
            rf"\newcommand{{\Mem{macro}}}{{{fmt_mem(mem)}}}",
        ]
    lines.append(rf"\newcommand{{\DeviceName}}{{{esc(device)}}}")
    n_train = int(df["subset_size"].iloc[0])
    lines.append(rf"\newcommand{{\SubsetSize}}{{{n_train:,}}}".replace(",", ","))
    with open(os.path.join(OUT, "vals.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")

    # ---- main results table ---------------------------------------------
    rows = []
    for name in RUN_ORDER:
        r = d.loc[name]
        rows.append(
            " & ".join([
                RUN_LABEL[name],
                fmt_mem(r["total_params"]),
                fmt_mem(r["trainable_params"]),
                f"{float(r['trainable_pct']):.3f}",
                rf"\textbf{{{float(r['best_val_acc'])*100:.2f}}}" if name == "full"
                else f"{float(r['best_val_acc'])*100:.2f}",
                fmt_mem(r["peak_gpu_mem_mib"]),
                f"{float(r['train_time_sec'])/60:.1f}",
            ]) + r" \\"
        )
    with open(os.path.join(OUT, "table_results.tex"), "w") as f:
        f.write("% AUTO-GENERATED by scripts/report_tables.py\n")
        # NOTE: the closing \hline lives inside this file on purpose -
        # some TeX engines reject an \hline placed after an \input'ed
        # file inside a tabular alignment.
        f.write("\n".join(rows) + "\n\\hline\n")

    # ---- per-epoch log table --------------------------------------------
    log = pd.read_csv(os.path.join(ROOT, "results", "experiment_log.csv"))
    log = log[log["run_name"].isin(RUN_ORDER)]
    log["_o"] = log["run_name"].map(lambda n: RUN_ORDER.index(n))
    rows = []
    for name in RUN_ORDER:
        sub = log[log["run_name"] == name].sort_values("epoch")
        for row in sub.itertuples():
            rows.append(
                " & ".join([
                    RUN_LABEL[name], str(int(row.epoch)),
                    f"{float(row.train_loss):.3f}", f"{float(row.train_acc)*100:.2f}",
                    f"{float(row.val_loss):.3f}", f"{float(row.val_acc)*100:.2f}",
                    f"{float(row.epoch_time_sec)/60:.1f}",
                ]) + r" \\"
            )
    with open(os.path.join(OUT, "table_epochs.tex"), "w") as f:
        f.write("% AUTO-GENERATED by scripts/report_tables.py\n")
        f.write("\n".join(rows) + "\n\\hline\n")

    # ---- optional cross-device (Colab T4) confirmation ------------------
    t4_path = os.path.join(ROOT, "results", "colab_t4", "results.csv")
    if os.path.exists(t4_path):
        t4 = pd.read_csv(t4_path).drop_duplicates(subset=["run_name"], keep="last")
        t4["peak_gpu_mem_mib"] = pd.to_numeric(t4["peak_gpu_mem_mib"], errors="coerce")
        t4["_o"] = t4["run_name"].map(lambda n: RUN_ORDER.index(n) if n in RUN_ORDER else 99)
        t = t4.sort_values("_o").set_index("run_name")
        assert set(RUN_ORDER) <= set(t.index), f"T4: missing runs {set(RUN_ORDER) - set(t.index)}"
        # derived constants (kept as macros so no number is hand-typed in report.tex)
        deltas = [(float(t.loc[n, "best_val_acc"]) - float(d.loc[n, "best_val_acc"]))
                  for n in RUN_ORDER]
        import math
        # percentage points, CEILed to 0.1 so "within X points" is a true bound
        max_delta = math.ceil(100.0 * max(abs(x) for x in deltas) * 10) / 10
        mem_ratio = (float(t.loc["full", "peak_gpu_mem_mib"])
                     / float(t.loc["lora_r4_a8", "peak_gpu_mem_mib"]))
        with open(os.path.join(OUT, "vals.tex"), "a") as f:
            f.write(f"% device={t4['device'].iloc[0]}, source=results/colab_t4/results.csv\n")
            for name, macro in RUN_MACRO.items():
                f.write(rf"\newcommand{{\ValT{macro}}}{{{float(t.loc[name, 'best_val_acc'])*100:.2f}\%}}" + "\n")
            for name, macro in [("full", "FULL"), ("lora_r4_a8", "RFOUR")]:
                f.write(rf"\newcommand{{\MemT{macro}}}{{{fmt_mem(t.loc[name, 'peak_gpu_mem_mib'])}}}" + "\n")
                f.write(rf"\newcommand{{\TimeT{macro}}}{{{float(t.loc[name, 'train_time_sec'])/60:.1f}}}" + "\n")
            f.write(rf"\newcommand{{\MaxDeltaT}}{{{max_delta:.1f}}}" + "\n")
            f.write(rf"\newcommand{{\MemRatioT}}{{{mem_ratio:.1f}}}" + "\n")
        rows = []
        for name in RUN_ORDER:
            r = t.loc[name]
            rows.append(" & ".join([
                RUN_LABEL[name],
                f"{float(r['best_val_acc'])*100:.2f}",
                fmt_mem(r["trainable_params"]),
                fmt_mem(r["peak_gpu_mem_mib"]),
                f"{float(r['train_time_sec'])/60:.1f}",
            ]) + r" \\")
        with open(os.path.join(OUT, "table_results_t4.tex"), "w") as f:
            f.write("% AUTO-GENERATED by scripts/report_tables.py (Colab T4 run)\n")
            f.write("\n".join(rows) + "\n\\hline\n")
        print(f"[report_tables] wrote T4 confirmation table (device={t4['device'].iloc[0]})")

    print(f"[report_tables] wrote vals.tex, table_results.tex, table_epochs.tex -> {OUT}")
    print(f"[report_tables] device={device}, subset={n_train}")
    for name in RUN_ORDER:
        r = d.loc[name]
        print(f"  {name:14s} acc={float(r['best_val_acc'])*100:5.2f}% "
              f"trainable={int(r['trainable_params']):>10,} "
              f"mem={fmt_mem(r['peak_gpu_mem_mib']):>4}MiB "
              f"time={float(r['train_time_sec'])/60:5.1f}min")
    return 0


if __name__ == "__main__":
    sys.exit(main())
